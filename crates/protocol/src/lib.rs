//! Norn's public wire protocol: the Rust form of `protobuf/`.
//!
//! # Layer contract
//!
//! - **Owns**: the message types and gRPC client and server stubs for every
//!   `norn.*.v1` package, generated from `protobuf/` by `just gen` and committed
//!   under `src/generated/`, plus the protocol version constants
//!   ([`PROTOCOL_VERSION`], [`VERSION_METADATA_KEY`]) and the shared-memory
//!   plane's metadata keys ([`DATA_PLANE_METADATA_KEY`],
//!   [`SHARED_MEMORY_SERVICE_METADATA_KEY`]). docs/reference/protocol.md is the
//!   reference for what the messages mean.
//! - **Must not**: hand-edit generated code; perform I/O; pick a transport
//!   (stubs are generic over any `tower` service, and the generated clients
//!   have no `connect`, by `no_transport`); convert to or from `norn-core`
//!   types yet, which is a later, separate module.
//! - **May import**: `prost`, `prost-types`, `tonic` (feature `codegen`
//!   only), `tonic-prost` and `tonic-types`, all pure Rust. Of the
//!   workspace: `norn-core`, which it does not need yet.
//! - **Spans**: none; the server and client layers trace calls.
//!
//! Concurrency: every message is plain owned data, `Send + Sync`. Clients
//! are `Clone`, and each clone may issue calls concurrently over the same
//! underlying service. Decoding never panics: malformed input is a
//! [`prost::DecodeError`].
//!
//! Building this crate needs neither `buf` nor `protoc`: the generated code
//! is checked in, and `just gen-check` fails when it is stale.

#[allow(
    missing_docs,
    unreachable_pub,
    clippy::all,
    clippy::pedantic,
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::indexing_slicing,
    rustdoc::all,
    dead_code,
    reason = "generated by protoc-gen-prost and protoc-gen-tonic; protobuf/ is where it is reviewed"
)]
mod generated;
mod plane;
mod version;

pub use plane::{
    DATA_PLANE_METADATA_KEY, DATA_PLANE_SHARED_MEMORY, SHARED_MEMORY_MINOR,
    SHARED_MEMORY_SERVICE_METADATA_KEY,
};
pub use version::{PROTOCOL_VERSION, ProtocolVersion, VERSION_METADATA_KEY};

/// Every file of `protobuf/` and the googleapis and MCP annotation files it imports,
/// as an encoded `google.protobuf.FileDescriptorSet` without source info. Built by
/// `just gen` (`buf build`) and checked by `just gen-check`. For server reflection,
/// and for mapping a message to and from its canonical JSON by name. Borrowed: a
/// `'static` slice in the binary, 73 KiB.
pub const FILE_DESCRIPTOR_SET: &[u8] = include_bytes!("norn.binpb");

/// `norn.admin.v1`: the daemon's description and protocol negotiation.
pub use generated::norn::admin::v1 as admin;
/// `norn.entity.v1`: the Entity resource and EntityService.
pub use generated::norn::entity::v1 as entity;
/// `norn.query.v1`: QueryService and its aggregations.
pub use generated::norn::query::v1 as query;
/// `norn.replay.v1`: ReplaySession resources and their clock controls.
pub use generated::norn::replay::v1 as replay;
/// `norn.signal.v1`: the Signal resource and SignalService.
pub use generated::norn::signal::v1 as signal;
/// `norn.state.v1`: StateService, the state of signals at an instant.
pub use generated::norn::state::v1 as state;
/// `norn.stream.v1`: the Stream resource, compaction and export.
pub use generated::norn::stream::v1 as stream;
/// `norn.telemetry.v1`: ingestion with backpressure, and subscriptions.
pub use generated::norn::telemetry::v1 as telemetry;
/// `norn.type`: Value, Quality, Sample and the error reasons, shared by every
/// package. Named `common` here because `type` is a Rust keyword.
pub use generated::norn::r#type as common;

/// The googleapis types the schema uses, generated with it so their prost
/// version is always this crate's: `google.longrunning` (long-running
/// operations), `google.type` (`Interval`) and `google.api` (annotations).
pub mod google {
    pub use super::generated::google::{api, longrunning, r#type};
}

/// `google.rpc`: `Status`, `ErrorInfo` and the other error details of the
