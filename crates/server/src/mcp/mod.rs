//! MCP inside the daemon: the tools protoc-gen-mcp generates from the
//! `(mcp.v1.tool)` annotations, one handler per service, combined into one endpoint
//! and served over stdio, loopback HTTP, a Unix socket or a named pipe.
//!
//! A tool's arguments are its RPC's request as JSON, and a call reaches the same
//! gRPC service a socket client does, through the server's in-process loopback, so
//! it passes the same layers. Only tools annotated read-only are served
//! ([`endpoint`]), and the rest have no path to the daemon ([`bridge`]).

mod bridge;
pub(crate) mod dial;
mod endpoint;
mod errors;
mod rpc;
mod sessions;
pub(crate) mod transport;

pub use tools::read_only_tool_names;

mod tools {
    /// The name of every tool the daemon serves, for a client to compare with.
    #[must_use]
    pub fn read_only_tool_names() -> Vec<String> {
        let tools = super::endpoint::Endpoint::tools();
        tools.into_iter().map(|t| t.name.to_string()).collect()
    }
}

/// Generated code is reviewed in the protos, not here.
macro_rules! generated {
    ($($name:ident => $path:literal,)*) => {
        #[allow(
            missing_docs, unreachable_pub, dead_code, unused_imports, clippy::all,
            clippy::pedantic, clippy::unwrap_used, clippy::expect_used, clippy::panic,
            clippy::indexing_slicing,
            reason = "generated by protoc-gen-mcp; the protos are where it is reviewed"
        )]
        pub(crate) mod generated {
            $(
                #[doc = concat!("Generated from `", $path, "`.")]
                pub(crate) mod $name {
                    include!(concat!("generated/norn/", $path));
                }
            )*
        }
    };
}

