# Norn's owner also authors protoc-gen-mcp and licenses this generated output
# under Norn's project terms. The pinned generator hardcodes its own project's
# header; apply the owner's Norn header as part of generation, never by hand.
set -euo pipefail
directory="${1:-crates/server/src/mcp/generated}"
count=0
temporary=""
trap 'if [[ -n "$temporary" ]]; then rm -f "$temporary"; fi' EXIT
while IFS= read -r -d '' file; do
  grep -Fq '// Code generated by protoc-gen-mcp. DO NOT EDIT.' "$file"
  if ! head -n 6 "$file" | grep -Eq '^// SPDX-License-Identifier: (Apache-2.0|AGPL-3.0-or-later)$'; then
    echo "unexpected MCP license header in $file" >&2; exit 1
  fi
  temporary="$(mktemp "${file}.XXXXXX")"
  sed '1,6{
    s|^// Copyright 2026 The Protobuf Project authors\.$|// SPDX-FileCopyrightText: 2026 Srikanth K|
    s|^// SPDX-License-Identifier: Apache-2.0$|// SPDX-License-Identifier: AGPL-3.0-or-later|
  }' "$file" > "$temporary"
  grep -Fq '// SPDX-FileCopyrightText: 2026 Srikanth K' "$temporary"
  cat "$temporary" > "$file"
  rm -f "$temporary"
  temporary=""
  count=$((count + 1))
done < <(find "$directory" -type f -name '*.mcp.rs' -print0)
if [[ "$count" == 0 ]]; then
  echo "no generated MCP handlers in $directory" >&2; exit 1
fi
echo "MCP project license headers: $count files"
